// Дюжины
export const DOZENS = [
  { label: '1-12',  from: 1,  to: 12 },
  { label: '13-24', from: 13, to: 24 },
  { label: '25-36', from: 25, to: 36 },
]

export function isInDozen(n, idx) {
  const d = DOZENS[idx]
  return n >= d.from && n <= d.to
}

export function isInColumn(n, col) {
  // col: 0, 1, 2 — снизу вверх (1,2,3 / 4,5,6 / ...)
  if (n === 0) return false
  return (n - 1) % 3 === col
}